"""Generate argument-model drafts for the editor ops (P0 WI-0.8, AD-14).

Usage:
    python scripts/tools/gen_op_schemas.py --check   # report op count and ops whose args are forwarded wholesale
    python scripts/tools/gen_op_schemas.py --write   # (re)write src/gameforge_ide/unreal/op_schemas_generated.py

The generated module is a *draft* derived from ``args.get("k", default)`` / ``args["k"]`` usage. Hand-reviewed models
live in ``op_schemas.py`` and take precedence over the generated ones.
"""
from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
PKG = REPO / "src/gameforge_ide/unreal/GameForge/Content/Python/gameforge_ops"
OUT = REPO / "src/gameforge_ide/unreal/op_schemas_generated.py"


def _op_name(fn: ast.FunctionDef):
    for d in fn.decorator_list:
        if isinstance(d, ast.Call) and getattr(d.func, "id", "") == "op":
            return d.args[0].value
    return None


def _type_of(default: ast.expr | None) -> str:
    if default is None:
        return "Any"
    if isinstance(default, ast.Constant):
        v = default.value
        if isinstance(v, bool):
            return "bool"
        if isinstance(v, int):
            return "float"  # JSON numbers: accept ints and floats
        if isinstance(v, float):
            return "float"
        if isinstance(v, str):
            return "str"
        if v is None:
            return "Any"
    if isinstance(default, (ast.List, ast.Tuple)):
        return "list"
    if isinstance(default, ast.Dict):
        return "dict"
    return "Any"


def collect() -> dict[str, dict]:
    ops: dict[str, dict] = {}
    for f in sorted(PKG.glob("*.py")):
        for n in ast.parse(f.read_text(encoding="utf-8")).body:
            if not isinstance(n, ast.FunctionDef) or not _op_name(n):
                continue
            param = n.args.args[0].arg if n.args.args else "args"
            keys: dict[str, tuple[str, str]] = {}
            forwarded = False
            for x in ast.walk(n):
                if isinstance(x, ast.Call) and isinstance(x.func, ast.Attribute) and x.func.attr == "get" \
                        and isinstance(x.func.value, ast.Name) and x.func.value.id == param \
                        and x.args and isinstance(x.args[0], ast.Constant):
                    d = x.args[1] if len(x.args) > 1 else None
                    keys[x.args[0].value] = ("optional", _type_of(d))
                elif isinstance(x, ast.Subscript) and isinstance(x.value, ast.Name) and x.value.id == param \
                        and isinstance(x.slice, ast.Constant):
                    keys.setdefault(x.slice.value, ("required", "Any"))
                elif isinstance(x, ast.Call):
                    passed = list(x.args) + [k.value for k in x.keywords]
                    if any(isinstance(v, ast.Name) and v.id == param for v in passed):
                        forwarded = True  # args handed to a helper that may read more keys
            ops[_op_name(n)] = {"keys": keys, "forwarded": forwarded, "module": f.stem}
    return ops


def render(ops: dict[str, dict]) -> str:
    lines = ['"""GENERATED by scripts/tools/gen_op_schemas.py - do not edit; override in op_schemas.py."""',
             "from __future__ import annotations", "", "import warnings", "from typing import Any", "",
             "from pydantic import BaseModel, ConfigDict", "",
             'warnings.filterwarnings("ignore", message=\'.*shadows an attribute in parent "BaseModel".*\', category=UserWarning)', "", ""]
    names = {}
    for op, info in sorted(ops.items()):
        cls = "".join(p.capitalize() for p in op.split("_")) + "Args"
        names[op] = cls
        lines.append(f"class {cls}(BaseModel):")
        manual = not info["keys"] or info["forwarded"]
        lines.append(f'    model_config = ConfigDict(extra="{"allow" if manual else "forbid"}")'
                     + ("  # MANUAL: args forwarded to a helper or none read" if manual else ""))
        for k, (kind, typ) in sorted(info["keys"].items()):
            # Every key is optional in the draft: a subscript read may sit inside a branch (e.g. spawn_actor's
            # light_intensity). Required-ness is decided in hand-reviewed models.
            lines.append(f"    {k}: {typ} | None = None")
        lines += ["", ""]
    lines.append("GENERATED: dict[str, type[BaseModel]] = {")
    lines += [f'    "{op}": {cls},' for op, cls in sorted(names.items())]
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    ops = collect()
    manual = sorted(o for o, i in ops.items() if not i["keys"] or i["forwarded"])
    print(f"{len(ops)} ops; {len(manual)} need manual review (no keys detected or args forwarded)")
    if a.write:
        OUT.write_text(render(ops), encoding="utf-8", newline="\n")
        print(f"wrote {OUT}")
    elif a.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != render(ops):
            print("DRIFT: op_schemas_generated.py is out of date; run --write")
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
