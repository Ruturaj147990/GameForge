from __future__ import annotations

from typing import Dict


def render_sources(p) -> Dict[str, str]:
    name = p.project_name
    api = name.upper() + "_API"

    config = CONFIG_H
    replacements = {
        "__TITLE__": p.display_title,
        "__DIFFICULTY__": p.difficulty,
        "__PLAYER_HP__": str(int(p.player_base_health)),
        "__OPPONENT_HP__": str(int(p.opponent_base_health)),
        "__STARTING_HAND__": str(int(p.starting_hand_size)),
        "__MAX_HAND__": str(int(p.max_hand_size)),
        "__BASE_ENERGY__": str(int(p.base_energy_per_turn)),
        "__LANE_COUNT__": str(int(p.lane_count)),
    }
    for k, v in replacements.items():
        config = config.replace(k, v)

    files = {
        "GFCardConfig.h": config,
        "GFCardTypes.h": TYPES_H,
        "GFCardStateComponent.h": STATE_COMP_H,
        "GFCardStateComponent.cpp": STATE_COMP_CPP,
        "GFCardOpponentAI.h": OPPONENT_AI_H,
        "GFCardOpponentAI.cpp": OPPONENT_AI_CPP,
        "GFCardGameMode.h": GAMEMODE_H,
        "GFCardGameMode.cpp": GAMEMODE_CPP,
        "GFCardHUD.h": HUD_H,
        "GFCardHUD.cpp": HUD_CPP,
        "GFCardTests.cpp": TESTS_CPP,
    }

    return {
        f"Source/{name}/{fn}": src.replace("__API__", api).replace("__NAME__", name)
        for fn, src in files.items()
    }


