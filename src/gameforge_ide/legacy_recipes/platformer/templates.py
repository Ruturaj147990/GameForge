COLLECTIBLE_CPP = r'''#include "GFPlatformerCollectible.h"
#include "GFPlatformerConfig.h"
#include "Components/SphereComponent.h"
#include "Components/StaticMeshComponent.h"
#include "GameFramework/RotatingMovementComponent.h"
#include "GFPlatformerGameMode.h"
#include "Kismet/GameplayStatics.h"
#include "UObject/ConstructorHelpers.h"

AGFPlatformerCollectible::AGFPlatformerCollectible()
	: bIsCollected(false)
{
	PrimaryActorTick.bCanEverTick = false;

	SphereCollision = CreateDefaultSubobject<USphereComponent>(TEXT("SphereCollision"));
	RootComponent = SphereCollision;
	SphereCollision->InitSphereRadius(45.0f);
	SphereCollision->SetCollisionProfileName(TEXT("OverlapAllDynamic"));
	SphereCollision->SetGenerateOverlapEvents(true);

	MeshComponent = CreateDefaultSubobject<UStaticMeshComponent>(TEXT("MeshComponent"));
	MeshComponent->SetupAttachment(RootComponent);
	MeshComponent->SetCollisionEnabled(ECollisionEnabled::NoCollision);

	static ConstructorHelpers::FObjectFinder<UStaticMesh> SphereMesh(TEXT("/Engine/BasicShapes/Sphere.Sphere"));
	if (SphereMesh.Succeeded())
	{
		MeshComponent->SetStaticMesh(SphereMesh.Object);
		MeshComponent->SetRelativeScale3D(FVector(0.5f, 0.5f, 0.5f));
	}

	RotatingMovement = CreateDefaultSubobject<URotatingMovementComponent>(TEXT("RotatingMovement"));
	RotatingMovement->RotationRate = FRotator(0.0f, 90.0f, 0.0f);

	SphereCollision->OnComponentBeginOverlap.AddDynamic(this, &AGFPlatformerCollectible::OnOverlapBegin);
}

void AGFPlatformerCollectible::OnOverlapBegin(UPrimitiveComponent* OverlappedComp, AActor* OtherActor,
                                              UPrimitiveComponent* OtherComp, int32 OtherBodyIndex,
                                              bool bFromSweep, const FHitResult& SweepResult)
{
	if (!bIsCollected && GFPlatformerIsPlayerPawn(OtherActor))
	{
		AttemptCollect(OtherActor);
	}
}

bool AGFPlatformerCollectible::AttemptCollect(AActor* Collector)
{
	if (bIsCollected)
	{
		return false;
	}

	bIsCollected = true;
	SphereCollision->SetCollisionEnabled(ECollisionEnabled::NoCollision);
	SetActorHiddenInGame(true);

	if (UWorld* World = GetWorld())
	{
		if (AGFPlatformerGameMode* GM = Cast<AGFPlatformerGameMode>(UGameplayStatics::GetGameMode(World)))
		{
			GM->OnCollectibleCollected(this);
		}
	}
	return true;
}

void AGFPlatformerCollectible::ResetCollectible()
{
	bIsCollected = false;
	SphereCollision->SetCollisionEnabled(ECollisionEnabled::QueryOnly);
	SetActorHiddenInGame(false);
}
'''

