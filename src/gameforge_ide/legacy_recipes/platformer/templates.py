"""C++ source templates for the platformer recipe (UE 5.7).

Generates real C++ gameplay classes for a 3D platformer:
  * GFPlatformerConfig.h
  * GFPlatformerCollectible.h / .cpp
  * GFPlatformerCheckpoint.h / .cpp
  * GFPlatformerGoal.h / .cpp
  * GFPlatformerCharacter.h / .cpp
  * GFPlatformerHUD.h / .cpp
  * GFPlatformerGameMode.h / .cpp
  * GFPlatformerTests.cpp
"""

from __future__ import annotations

from typing import Dict


def render_sources(p) -> Dict[str, str]:
    name = p.project_name
    api = name.upper() + "_API"

    config = CONFIG_H
    replacements = {
        "__TITLE__": p.display_title,
        "__TARGET__": str(int(p.collectible_target)),
        "__DIFFICULTY__": p.difficulty,
        "__SPEED__": f"{float(p.player_speed):.1f}f",
        "__JUMP__": f"{float(p.jump_velocity):.1f}f",
        "__GRAV__": f"{float(p.gravity_scale):.2f}f",
        "__AIR__": f"{float(p.air_control):.2f}f",
        "__KILLZ__": f"{float(p.kill_z):.1f}f",
    }
    for k, v in replacements.items():
        config = config.replace(k, v)

    files = {
        "GFPlatformerConfig.h": config,
        "GFPlatformerCollectible.h": COLLECTIBLE_H,
        "GFPlatformerCollectible.cpp": COLLECTIBLE_CPP,
        "GFPlatformerCheckpoint.h": CHECKPOINT_H,
        "GFPlatformerCheckpoint.cpp": CHECKPOINT_CPP,
        "GFPlatformerGoal.h": GOAL_H,
        "GFPlatformerGoal.cpp": GOAL_CPP,
        "GFPlatformerCharacter.h": CHARACTER_H,
        "GFPlatformerCharacter.cpp": CHARACTER_CPP,
        "GFPlatformerHUD.h": HUD_H,
        "GFPlatformerHUD.cpp": HUD_CPP,
        "GFPlatformerGameMode.h": GAMEMODE_H,
        "GFPlatformerGameMode.cpp": GAMEMODE_CPP,
        "GFPlatformerTests.cpp": TESTS_CPP,
    }

    return {
        f"Source/{name}/{fn}": src.replace("__API__", api).replace("__NAME__", name)
        for fn, src in files.items()
    }


CONFIG_H = r'''#pragma once

#include "CoreMinimal.h"

#include "GameFramework/Pawn.h"

// Generated by GameForge recipe platformer.
namespace GFPlatformerConfig
{
	inline const TCHAR* Title() { return TEXT("__TITLE__"); }
	constexpr int32 CollectibleTarget = __TARGET__;
	inline const TCHAR* Difficulty() { return TEXT("__DIFFICULTY__"); }
	constexpr float PlayerWalkSpeed = __SPEED__;
	constexpr float PlayerJumpZ = __JUMP__;
	constexpr float GravityScale = __GRAV__;
	constexpr float AirControl = __AIR__;
	constexpr float KillZ = __KILLZ__;
}

/** Gameplay transition marker for external verification of real input (read from the game log). */
#define GF_EVENT(Format, ...) UE_LOG(LogTemp, Display, TEXT("GF_EVENT " Format), ##__VA_ARGS__)

/** Only the player's own pawn may trigger collectibles, checkpoints and the goal. */
inline bool GFPlatformerIsPlayerPawn(const AActor* Actor)
{
	const APawn* Pawn = Cast<APawn>(Actor);
	return Pawn && Pawn->IsPlayerControlled();
}
'''

