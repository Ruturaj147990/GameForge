"""C++ source templates for the procedural_world recipe (UE 5.7).

Generates real C++ gameplay classes for a procedural landscape exploration environment:
  * GFProceduralConfig.h
  * GFProceduralLandmark.h / .cpp
  * GFProceduralCharacter.h / .cpp
  * GFProceduralHUD.h / .cpp
  * GFProceduralGameMode.h / .cpp
  * GFProceduralTests.cpp
"""

from __future__ import annotations

from typing import Dict


def render_sources(p) -> Dict[str, str]:
    name = p.project_name
    api = name.upper() + "_API"

    config = CONFIG_H
    replacements = {
        "__TITLE__": p.display_title,
        "__SEED__": str(int(p.seed)),
        "__TERRAIN__": p.terrain_type,
        "__ELEVATION__": f"{float(p.elevation_scale):.1f}f",
        "__ROAD_WIDTH__": f"{float(p.road_width):.1f}f",
        "__FOLIAGE_COUNT__": str(int(p.foliage_density)),
        "__LANDMARK_TYPE__": p.landmark_type,
        "__SPEED__": f"{float(p.player_speed):.1f}f",
    }
    for k, v in replacements.items():
        config = config.replace(k, v)

    files = {
        "GFProceduralConfig.h": config,
        "GFProceduralLandmark.h": LANDMARK_H,
        "GFProceduralLandmark.cpp": LANDMARK_CPP,
        "GFProceduralCharacter.h": CHARACTER_H,
        "GFProceduralCharacter.cpp": CHARACTER_CPP,
        "GFProceduralHUD.h": HUD_H,
        "GFProceduralHUD.cpp": HUD_CPP,
        "GFProceduralGameMode.h": GAMEMODE_H,
        "GFProceduralGameMode.cpp": GAMEMODE_CPP,
        "GFProceduralTests.cpp": TESTS_CPP,
    }

    return {
        f"Source/{name}/{fn}": src.replace("__API__", api).replace("__NAME__", name)
        for fn, src in files.items()
    }


CONFIG_H = r'''#pragma once

#include "CoreMinimal.h"

// Generated by GameForge recipe procedural_world.
namespace GFProceduralConfig
{
	inline const TCHAR* Title() { return TEXT("__TITLE__"); }
	constexpr int32 Seed = __SEED__;
	inline const TCHAR* TerrainType() { return TEXT("__TERRAIN__"); }
	constexpr float ElevationScale = __ELEVATION__;
	constexpr float RoadWidth = __ROAD_WIDTH__;
	constexpr int32 FoliageCount = __FOLIAGE_COUNT__;
	inline const TCHAR* LandmarkType() { return TEXT("__LANDMARK_TYPE__"); }
	constexpr float PlayerWalkSpeed = __SPEED__;
}

/** Gameplay transition marker for external verification of real input (read from the game log). */
#define GF_EVENT(Format, ...) UE_LOG(LogTemp, Display, TEXT("GF_EVENT " Format), ##__VA_ARGS__)
'''

