CHARACTER_CPP = r'''#include "GFProceduralCharacter.h"
#include "GFProceduralGameMode.h"
#include "Kismet/GameplayStatics.h"
#include "GameFramework/SpringArmComponent.h"
#include "Camera/CameraComponent.h"
#include "GameFramework/CharacterMovementComponent.h"
#include "GFProceduralConfig.h"

AGFProceduralCharacter::AGFProceduralCharacter()
	: TotalDistanceTraveled(0.0f)
{
	PrimaryActorTick.bCanEverTick = true;

	bUseControllerRotationPitch = false;
	bUseControllerRotationYaw = false;
	bUseControllerRotationRoll = false;

	GetCharacterMovement()->bOrientRotationToMovement = true;
	GetCharacterMovement()->RotationRate = FRotator(0.0f, 540.0f, 0.0f);
	GetCharacterMovement()->MaxWalkSpeed = GFProceduralConfig::PlayerWalkSpeed;
	GetCharacterMovement()->JumpZVelocity = 550.0f;
	GetCharacterMovement()->AirControl = 0.25f;

	CameraBoom = CreateDefaultSubobject<USpringArmComponent>(TEXT("CameraBoom"));
	CameraBoom->SetupAttachment(RootComponent);
	CameraBoom->TargetArmLength = 450.0f;
	CameraBoom->bUsePawnControlRotation = true;
	CameraBoom->SetRelativeLocation(FVector(0.0f, 0.0f, 75.0f));

	FollowCamera = CreateDefaultSubobject<UCameraComponent>(TEXT("FollowCamera"));
	FollowCamera->SetupAttachment(CameraBoom, USpringArmComponent::SocketName);
	FollowCamera->bUsePawnControlRotation = false;
}

void AGFProceduralCharacter::BeginPlay()
{
	Super::BeginPlay();
	StartLocation = GetActorLocation();
	LastTrackedLocation = StartLocation;
}

void AGFProceduralCharacter::Tick(float DeltaTime)
{
	Super::Tick(DeltaTime);

	const FVector CurrentLoc = GetActorLocation();
	const float StepDist = FVector::Dist2D(CurrentLoc, LastTrackedLocation);
	if (StepDist > 5.0f)
	{
		TotalDistanceTraveled += StepDist;
		LastTrackedLocation = CurrentLoc;
		OnTraversalDistanceChanged.Broadcast(TotalDistanceTraveled);
	}
	GFReportMovement();
}

void AGFProceduralCharacter::OnJumped_Implementation()
{
	Super::OnJumped_Implementation();
	GF_EVENT("jump z=%.0f", GetActorLocation().Z);
}

void AGFProceduralCharacter::RequestWorldReset()
{
	if (AGFProceduralGameMode* GM = Cast<AGFProceduralGameMode>(UGameplayStatics::GetGameMode(this)))
	{
		GM->ResetWorld();
	}
	else
	{
		ResetTraversal();
	}
}

void AGFProceduralCharacter::GFReportMovement()
{
	const FVector L = GetActorLocation();
	if (!bGFLocationReported || FVector::Dist2D(L, GFLastReportedLocation) > 100.0f)
	{
		GF_EVENT("moved x=%.0f y=%.0f z=%.0f", L.X, L.Y, L.Z);
		GFLastReportedLocation = L;
		bGFLocationReported = true;
	}
}

void AGFProceduralCharacter::SetupPlayerInputComponent(UInputComponent* PlayerInputComponent)
{
	Super::SetupPlayerInputComponent(PlayerInputComponent);

	PlayerInputComponent->BindAxis(TEXT("MoveForward"), this, &AGFProceduralCharacter::MoveForward);
	PlayerInputComponent->BindAxis(TEXT("MoveRight"), this, &AGFProceduralCharacter::MoveRight);
	PlayerInputComponent->BindAxis(TEXT("Turn"), this, &APawn::AddControllerYawInput);
	PlayerInputComponent->BindAxis(TEXT("LookUp"), this, &APawn::AddControllerPitchInput);
	PlayerInputComponent->BindAction(TEXT("Jump"), IE_Pressed, this, &ACharacter::Jump);
	PlayerInputComponent->BindAction(TEXT("Jump"), IE_Released, this, &ACharacter::StopJumping);
	PlayerInputComponent->BindAction(TEXT("Restart"), IE_Pressed, this, &AGFProceduralCharacter::RequestWorldReset);
}

void AGFProceduralCharacter::MoveForward(float Value)
{
	if (Controller && Value != 0.0f)
	{
		const FRotator Rotation = Controller->GetControlRotation();
		const FRotator YawRotation(0.0f, Rotation.Yaw, 0.0f);
		const FVector Direction = FRotationMatrix(YawRotation).GetUnitAxis(EAxis::X);
		AddMovementInput(Direction, Value);
	}
}

void AGFProceduralCharacter::MoveRight(float Value)
{
	if (Controller && Value != 0.0f)
	{
		const FRotator Rotation = Controller->GetControlRotation();
		const FRotator YawRotation(0.0f, Rotation.Yaw, 0.0f);
		const FVector Direction = FRotationMatrix(YawRotation).GetUnitAxis(EAxis::Y);
		AddMovementInput(Direction, Value);
	}
}

void AGFProceduralCharacter::ResetTraversal()
{
	SetActorLocation(StartLocation);
	GetCharacterMovement()->StopMovementImmediately();
	TotalDistanceTraveled = 0.0f;
	LastTrackedLocation = StartLocation;
	OnTraversalDistanceChanged.Broadcast(0.0f);
}
'''

