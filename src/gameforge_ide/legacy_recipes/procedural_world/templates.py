LANDMARK_CPP = r'''#include "GFProceduralLandmark.h"
#include "Components/BoxComponent.h"
#include "GameFramework/Character.h"

AGFProceduralLandmark::AGFProceduralLandmark()
	: LandmarkName(TEXT("Ancient Ruins"))
	, bDiscovered(false)
{
	PrimaryActorTick.bCanEverTick = false;

	SceneRoot = CreateDefaultSubobject<USceneComponent>(TEXT("SceneRoot"));
	RootComponent = SceneRoot;

	TriggerBox = CreateDefaultSubobject<UBoxComponent>(TEXT("TriggerBox"));
	TriggerBox->SetupAttachment(RootComponent);
	TriggerBox->SetBoxExtent(FVector(600.0f, 600.0f, 350.0f));
	TriggerBox->SetCollisionProfileName(TEXT("Trigger"));
	TriggerBox->OnComponentBeginOverlap.AddDynamic(this, &AGFProceduralLandmark::OnTriggerOverlap);
}

void AGFProceduralLandmark::OnTriggerOverlap(UPrimitiveComponent* OverlappedComp, AActor* OtherActor,
                                             UPrimitiveComponent* OtherComp, int32 OtherBodyIndex,
                                             bool bFromSweep, const FHitResult& SweepResult)
{
	if (!bDiscovered && OtherActor && OtherActor->IsA<ACharacter>())
	{
		TriggerDiscovery(OtherActor);
	}
}

bool AGFProceduralLandmark::TriggerDiscovery(AActor* Initiator)
{
	if (bDiscovered)
	{
		return false;
	}
	bDiscovered = true;
	OnLandmarkDiscovered.Broadcast(LandmarkName);
	return true;
}

void AGFProceduralLandmark::ResetLandmark()
{
	bDiscovered = false;
}
'''

