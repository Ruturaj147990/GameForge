from __future__ import annotations

from typing import Dict


def render_sources(p) -> Dict[str, str]:
    name = p.project_name
    api = name.upper() + "_API"

    config = CONFIG_H
    replacements = {
        "__TITLE__": p.display_title,
        "__DIFFICULTY__": p.difficulty,
        "__WAVES__": str(int(p.wave_count)),
        "__ENEMIES_PER_WAVE__": str(int(p.enemies_per_wave)),
        "__PLAYER_HEALTH__": f"{float(p.player_max_health):.1f}f",
        "__PLAYER_DMG__": f"{float(p.player_attack_damage):.1f}f",
        "__PLAYER_RANGE__": f"{float(p.player_attack_range):.1f}f",
        "__PLAYER_CD__": f"{float(p.player_attack_cooldown):.2f}f",
        "__ENEMY_HEALTH__": f"{float(p.enemy_max_health):.1f}f",
        "__ENEMY_DMG__": f"{float(p.enemy_attack_damage):.1f}f",
        "__ENEMY_RANGE__": f"{float(p.enemy_attack_range):.1f}f",
        "__ENEMY_CD__": f"{float(p.enemy_attack_cooldown):.2f}f",
        "__ENEMY_SPEED__": f"{float(p.enemy_speed):.1f}f",
    }
    for k, v in replacements.items():
        config = config.replace(k, v)

    files = {
        "GFArenaConfig.h": config,
        "GFArenaCharacter.h": CHARACTER_H,
        "GFArenaCharacter.cpp": CHARACTER_CPP,
        "GFArenaAIController.h": AICONTROLLER_H,
        "GFArenaAIController.cpp": AICONTROLLER_CPP,
        "GFArenaEnemy.h": ENEMY_H,
        "GFArenaEnemy.cpp": ENEMY_CPP,
        "GFArenaHUD.h": HUD_H,
        "GFArenaHUD.cpp": HUD_CPP,
        "GFArenaGameMode.h": GAMEMODE_H,
        "GFArenaGameMode.cpp": GAMEMODE_CPP,
        "GFArenaTests.cpp": TESTS_CPP,
    }

    return {
        f"Source/{name}/{fn}": src.replace("__API__", api).replace("__NAME__", name)
        for fn, src in files.items()
    }


