CHARACTER_CPP = r'''#include "GFPlatformerCharacter.h"
#include "Camera/CameraComponent.h"
#include "Components/CapsuleComponent.h"
#include "GameFramework/CharacterMovementComponent.h"
#include "GameFramework/SpringArmComponent.h"
#include "GFPlatformerConfig.h"
#include "GFPlatformerGameMode.h"
#include "Kismet/GameplayStatics.h"

AGFPlatformerCharacter::AGFPlatformerCharacter()
	: CurrentCheckpointIndex(0)
{
	PrimaryActorTick.bCanEverTick = true;

	GetCapsuleComponent()->InitCapsuleSize(42.0f, 96.0f);

	bUseControllerRotationPitch = false;
	bUseControllerRotationYaw = false;
	bUseControllerRotationRoll = false;

	GetCharacterMovement()->bOrientRotationToMovement = true;
	GetCharacterMovement()->RotationRate = FRotator(0.0f, 540.0f, 0.0f);
	GetCharacterMovement()->MaxWalkSpeed = GFPlatformerConfig::PlayerWalkSpeed;
	GetCharacterMovement()->JumpZVelocity = GFPlatformerConfig::PlayerJumpZ;
	GetCharacterMovement()->GravityScale = GFPlatformerConfig::GravityScale;
	GetCharacterMovement()->AirControl = GFPlatformerConfig::AirControl;

	CameraBoom = CreateDefaultSubobject<USpringArmComponent>(TEXT("CameraBoom"));
	CameraBoom->SetupAttachment(RootComponent);
	CameraBoom->TargetArmLength = 400.0f;
	CameraBoom->bUsePawnControlRotation = true;
	CameraBoom->bDoCollisionTest = true;

	FollowCamera = CreateDefaultSubobject<UCameraComponent>(TEXT("FollowCamera"));
	FollowCamera->SetupAttachment(CameraBoom, USpringArmComponent::SocketName);
	FollowCamera->bUsePawnControlRotation = false;
}

void AGFPlatformerCharacter::BeginPlay()
{
	Super::BeginPlay();
	SpawnLocation = GetActorLocation();
	ActiveCheckpointLocation = SpawnLocation;
}

void AGFPlatformerCharacter::Tick(float DeltaSeconds)
{
	Super::Tick(DeltaSeconds);

	if (GetActorLocation().Z < GFPlatformerConfig::KillZ)
	{
		RespawnAtCheckpoint();
	}
}

void AGFPlatformerCharacter::SetupPlayerInputComponent(UInputComponent* PlayerInputComponent)
{
	Super::SetupPlayerInputComponent(PlayerInputComponent);

	if (PlayerInputComponent)
	{
		PlayerInputComponent->BindAxis(TEXT("MoveForward"), this, &AGFPlatformerCharacter::MoveForward);
		PlayerInputComponent->BindAxis(TEXT("MoveRight"), this, &AGFPlatformerCharacter::MoveRight);
		PlayerInputComponent->BindAxis(TEXT("Turn"), this, &APawn::AddControllerYawInput);
		PlayerInputComponent->BindAxis(TEXT("LookUp"), this, &APawn::AddControllerPitchInput);
		PlayerInputComponent->BindAction(TEXT("Jump"), IE_Pressed, this, &AGFPlatformerCharacter::StartJump);
		PlayerInputComponent->BindAction(TEXT("Jump"), IE_Released, this, &AGFPlatformerCharacter::StopJump);
		PlayerInputComponent->BindAction(TEXT("Restart"), IE_Pressed, this, &AGFPlatformerCharacter::RestartLevel);
	}
}

void AGFPlatformerCharacter::MoveForward(float Value)
{
	if (Controller && Value != 0.0f)
	{
		const FRotator Rotation = Controller->GetControlRotation();
		const FRotator YawRotation(0.0f, Rotation.Yaw, 0.0f);
		const FVector Direction = FRotationMatrix(YawRotation).GetUnitAxis(EAxis::X);
		AddMovementInput(Direction, Value);
	}
}

void AGFPlatformerCharacter::MoveRight(float Value)
{
	if (Controller && Value != 0.0f)
	{
		const FRotator Rotation = Controller->GetControlRotation();
		const FRotator YawRotation(0.0f, Rotation.Yaw, 0.0f);
		const FVector Direction = FRotationMatrix(YawRotation).GetUnitAxis(EAxis::Y);
		AddMovementInput(Direction, Value);
	}
}

void AGFPlatformerCharacter::StartJump()
{
	if (CanJump())
	{
		Jump();
	}
}

void AGFPlatformerCharacter::StopJump()
{
	StopJumping();
}

void AGFPlatformerCharacter::RestartLevel()
{
	if (UWorld* World = GetWorld())
	{
		if (AGFPlatformerGameMode* GM = Cast<AGFPlatformerGameMode>(UGameplayStatics::GetGameMode(World)))
		{
			GM->ResetPlatformer();
		}
	}
}

void AGFPlatformerCharacter::SetActiveCheckpoint(int32 Index, const FVector& Location)
{
	CurrentCheckpointIndex = Index;
	ActiveCheckpointLocation = Location + FVector(0.0f, 0.0f, 20.0f);
}

void AGFPlatformerCharacter::RespawnAtCheckpoint()
{
	if (GetCharacterMovement())
	{
		GetCharacterMovement()->Velocity = FVector::ZeroVector;
	}
	SetActorLocation(ActiveCheckpointLocation, false, nullptr, ETeleportType::TeleportPhysics);
}
'''

